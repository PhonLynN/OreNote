package com.phonlynn.oreplan.v2.ai

/**
 * 对话模式（设计稿输入框里的 `[聊天|助手]` 分段控件）。
 *
 * ## 两个模式的区别
 *
 * · [CHAT] —— 纯对话。**请求里根本不带工具定义**，所以物理上不可能读写数据。
 *   这是机制上的保证，不是靠提示词约束模型"别调工具"。
 * · [ASSISTANT] —— 能用工具读写数据（工具集已接上）。
 *
 * 实现点只有一处：`SendChatMessage(toolsEnabled = mode == ASSISTANT)`，
 * 它决定请求里发不发 `tools` 字段。
 *
 * ## ⚠️ 默认是 [CHAT]
 *
 * 也就是说**不切到「助手」就不会调任何工具** —— 这是刻意的（"聊天模式不碰数据"
 * 要成为默认安全的那一侧）。但它也意味着"AI 好像不会用工具"的第一嫌疑
 * 是模式没切，不是工具坏了。
 *
 * 切换的语义（已定）：**中途切换等到当前这轮结束再真正生效**，
 * 且**只改变接下来的行为，对历史毫无影响**。
 */
enum class ChatMode(val label: String) {
    CHAT("聊天"),
    ASSISTANT("助手"),
}
